using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using Ballverse.App;
using UnityEditor.Android;
using UnityEditor.Build;

namespace Ballverse.Editor
{
    /// <summary>
    /// Android backup rules (spec §3.9): Auto Backup and device-to-device transfer include only the settings and
    /// presets folders, never projects (they hold copies of user videos, far over the 25 MB Auto Backup quota, which
    /// would make Android skip the whole backup) or logs.
    /// <para>
    /// After Unity generates the Gradle project, this writes two XML resources into the launcher (application) module:
    /// <c>full-backup-content</c> (Android 8–11) and <c>data-extraction-rules</c> (Android 12+), and points the
    /// launcher manifest's &lt;application&gt; at them. The launcher manifest has the highest priority in Gradle's manifest
    /// merge and the attributes are marked <c>tools:replace</c>, so a library manifest cannot override them.
    /// Application.persistentDataPath is getExternalFilesDir() on most devices and getFilesDir() on the rest, so
    /// both the "external" and the "file" domains are listed.
    /// </para>
    /// </summary>
    public sealed class AndroidBackupRules : IPostGenerateGradleAndroidProject
    {
        public const string FullBackupContentName = "ballverse_backup_rules";
        public const string DataExtractionRulesName = "ballverse_data_extraction_rules";

        const string AndroidNs = "http://schemas.android.com/apk/res/android";
        const string ToolsNs = "http://schemas.android.com/tools";

        /// <summary>Folders under the persistent data root that are backed up, nothing else.</summary>
        public static readonly IReadOnlyList<string> BackedUpDirs = new[] { AppPaths.SettingsDirName, AppPaths.PresetsDirName };

        /// <summary>Backup domains that can hold Application.persistentDataPath.</summary>
        public static readonly IReadOnlyList<string> Domains = new[] { "file", "external" };

        /// <summary>Attributes written on &lt;application&gt; and their values.</summary>
        public static readonly IReadOnlyList<KeyValuePair<string, string>> ApplicationAttributes = new[]
        {
            new KeyValuePair<string, string>("allowBackup", "true"),
            new KeyValuePair<string, string>("fullBackupContent", "@xml/" + FullBackupContentName),
            new KeyValuePair<string, string>("dataExtractionRules", "@xml/" + DataExtractionRulesName),
        };

        // After the media plugin's unityLibrary manifest patch (100); this one edits the launcher module only.
        public int callbackOrder => 200;

        public void OnPostGenerateGradleAndroidProject(string path)
        {
            string libraryDir = Path.GetFullPath(path).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            string launcherDir = Path.Combine(Path.GetDirectoryName(libraryDir) ?? libraryDir, "launcher");
            string manifestPath = Path.Combine(launcherDir, "src", "main", "AndroidManifest.xml");
            if (!File.Exists(manifestPath))
                throw new BuildFailedException("[Ballverse] Launcher manifest not found at " + manifestPath + "; cannot apply the Android backup rules (spec §3.9).");

            string xmlDir = Path.Combine(launcherDir, "src", "main", "res", "xml");
            Directory.CreateDirectory(xmlDir);
            var utf8 = new UTF8Encoding(false);
            File.WriteAllText(Path.Combine(xmlDir, FullBackupContentName + ".xml"), FullBackupContentXml(), utf8);
            File.WriteAllText(Path.Combine(xmlDir, DataExtractionRulesName + ".xml"), DataExtractionRulesXml(), utf8);

            var doc = new XmlDocument();
            doc.Load(manifestPath);
            PatchManifest(doc);
            var settings = new XmlWriterSettings { Encoding = utf8, Indent = true };
            using (XmlWriter writer = XmlWriter.Create(manifestPath, settings))
            {
                doc.Save(writer);
            }
        }

        /// <summary>res/xml/ballverse_backup_rules.xml (android:fullBackupContent, Android 6–11).</summary>
        public static string FullBackupContentXml()
        {
            var sb = new StringBuilder();
            sb.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
            sb.Append("<!-- Generated by Ballverse.Editor.AndroidBackupRules (spec §3.9): only settings and presets are backed up. -->\n");
            sb.Append("<full-backup-content>\n");
            AppendIncludes(sb, "    ");
            sb.Append("</full-backup-content>\n");
            return sb.ToString();
        }

        /// <summary>res/xml/ballverse_data_extraction_rules.xml (android:dataExtractionRules, Android 12+).</summary>
        public static string DataExtractionRulesXml()
        {
            var sb = new StringBuilder();
            sb.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
            sb.Append("<!-- Generated by Ballverse.Editor.AndroidBackupRules (spec §3.9): only settings and presets are backed up or transferred. -->\n");
            sb.Append("<data-extraction-rules>\n");
            foreach (string section in new[] { "cloud-backup", "device-transfer" })
            {
                sb.Append("    <").Append(section).Append(">\n");
                AppendIncludes(sb, "        ");
                sb.Append("    </").Append(section).Append(">\n");
            }
            sb.Append("</data-extraction-rules>\n");
            return sb.ToString();
        }

        // With at least one <include>, Android backs up only the included paths.
        static void AppendIncludes(StringBuilder sb, string indent)
        {
            foreach (string domain in Domains)
            {
                foreach (string dir in BackedUpDirs)
                {
                    sb.Append(indent).Append("<include domain=\"").Append(domain).Append("\" path=\"").Append(dir).Append("\" />\n");
                }
            }
        }

        /// <summary>Sets the backup attributes on the manifest's &lt;application&gt; (created if missing). Idempotent.</summary>
        public static void PatchManifest(XmlDocument doc)
        {
            if (doc == null) throw new ArgumentNullException(nameof(doc));
            XmlElement root = doc.DocumentElement;
            if (root == null || root.Name != "manifest") throw new InvalidOperationException("Not an Android manifest: the root element must be <manifest>.");
            if (!root.HasAttribute("xmlns:android")) root.SetAttribute("xmlns:android", AndroidNs);
            if (!root.HasAttribute("xmlns:tools")) root.SetAttribute("xmlns:tools", ToolsNs);

            XmlElement app = root["application"];
            if (app == null)
            {
                app = doc.CreateElement("application");
                root.AppendChild(app);
            }

            foreach (KeyValuePair<string, string> attribute in ApplicationAttributes)
            {
                XmlAttribute existing = app.GetAttributeNode(attribute.Key, AndroidNs);
                if (existing != null)
                {
                    existing.Value = attribute.Value;
                    continue;
                }
                XmlAttribute created = doc.CreateAttribute("android", attribute.Key, AndroidNs);
                created.Value = attribute.Value;
                app.Attributes.Append(created);
            }

            var replace = new List<string>();
            string current = app.GetAttribute("replace", ToolsNs);
            if (!string.IsNullOrEmpty(current))
                replace.AddRange(current.Split(',').Select(s => s.Trim()).Where(s => s.Length > 0));
            foreach (KeyValuePair<string, string> attribute in ApplicationAttributes)
            {
                string name = "android:" + attribute.Key;
                if (!replace.Contains(name)) replace.Add(name);
            }
            XmlAttribute replaceAttribute = app.GetAttributeNode("replace", ToolsNs);
            if (replaceAttribute == null)
            {
                replaceAttribute = doc.CreateAttribute("tools", "replace", ToolsNs);
                app.Attributes.Append(replaceAttribute);
            }
            replaceAttribute.Value = string.Join(",", replace);
        }
    }
}
