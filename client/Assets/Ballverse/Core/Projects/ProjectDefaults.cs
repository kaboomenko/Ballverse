using System;
using System.Collections.Generic;

namespace Ballverse.Core.Projects
{
    /// <summary>Default values and the factory for new projects (spec §3.9, §7.4).</summary>
    public static class ProjectDefaults
    {
        public const string Font = "manrope_black";
        public const string DividerColor = "#FFFFFF33";
        public const string TextFill = "#FFFFFF";
        public const string StrokeColor = "#000000";
        public const string UntitledName = "Untitled";
        /// <summary>Fallback for timestamps that cannot be parsed.</summary>
        public const string EpochIso = "1970-01-01T00:00:00Z";

        /// <summary>
        /// New project document: clip with the given length, no user video, default L1 layout (spec §3.3 "по умолч."),
        /// watermark opt-in off (see <see cref="WatermarkPolicy"/>), empty texts and history.
        /// </summary>
        /// <param name="id">Folder id (<see cref="ProjectPaths.IsSafeId"/>), generated by the caller.</param>
        /// <param name="name">User-visible name.</param>
        /// <param name="nowIso">ISO-8601 timestamp used for createdAt and updatedAt.</param>
        /// <param name="modeId">Mode of the recorded clip.</param>
        /// <param name="clipTicks">Recorded clip length in ticks (trimOutTick), clamped to the run cap.</param>
        public static ProjectDocument NewProject(string id, string name, string nowIso, string modeId, int clipTicks = SimConstants.MaxDurationTicks)
        {
            return new ProjectDocument
            {
                SchemaVersion = ProjectMigrator.CurrentSchemaVersion,
                Id = id,
                Name = name,
                CreatedAt = nowIso,
                UpdatedAt = nowIso,
                Clip = new ClipSettings
                {
                    Replay = ProjectPaths.ClipReplayFile,
                    ModeId = modeId,
                    TrimInTick = 0,
                    TrimOutTick = Math.Max(1, Math.Min(clipTicks, SimConstants.MaxDurationTicks)),
                    Speed = 1.0,
                    FinaleSlowMo = new FinaleSlowMo(),
                    AfterEnd = SimAfterEnd.Freeze,
                },
                UserVideo = null,
                Layout = new LayoutSettings { Type = LayoutType.L1 },
                Texts = new List<TextLayer>(),
                Audio = new AudioSettings(),
                Output = new OutputSettings(),
                Exports = new List<ExportRecord>(),
            };
        }

        /// <summary>Default PiP window used when L3/L5 has no pip block.</summary>
        public static PipSettings Pip()
        {
            return new PipSettings();
        }
    }
}
